(function() {
    var totalSlides = 22;
    var currentSlide = 1;
    var ejeMapping = {
        1: [1, 2, 3, 4],
        2: [5, 6, 7, 8, 9],
        3: [10, 11, 12, 13],
        4: [14, 15],
        5: [16],
        6: [17, 18, 19, 20, 21, 22]
    };

    window.goToC8Slide = function(slideNum, shouldScroll) {
        if (slideNum < 1 || slideNum > totalSlides) return;
        currentSlide = slideNum;

        // 1. Highlight pill
        document.querySelectorAll('.c8-pill-btn').forEach(function(btn) {
            var n = parseInt(btn.getAttribute('data-c8-slide'));
            if (n === currentSlide) {
                btn.classList.add('active');
                btn.style.background = '#F39200';
                btn.style.color = '#FFFFFF';
                btn.style.borderColor = '#F39200';
            } else {
                btn.classList.remove('active');
                btn.style.background = '#FFFFFF';
                btn.style.color = '#1A1A1B';
                btn.style.borderColor = '#CBD5E1';
            }
        });

        // 2. Highlight Eje
        var currentEjeId = 1;
        for (var eId in ejeMapping) {
            if (ejeMapping[eId].indexOf(currentSlide) !== -1) {
                currentEjeId = parseInt(eId);
                break;
            }
        }
        document.querySelectorAll('.c8-eje-btn').forEach(function(btn) {
            var eId = parseInt(btn.getAttribute('data-c8-eje'));
            if (eId === currentEjeId) {
                btn.classList.add('active');
                btn.style.background = '#1A1A1B';
                btn.style.color = '#FFFFFF';
                btn.style.border = '1.5px solid #F39200';
            } else {
                btn.classList.remove('active');
                btn.style.background = '#FFFFFF';
                btn.style.color = '#4A4A4A';
                btn.style.border = '1px solid #E2E8F0';
            }
        });

        // 3. Show slide panel
        document.querySelectorAll('.c8-slide-panel').forEach(function(panel) {
            panel.classList.remove('active');
            panel.style.display = 'none';
        });
        var targetPanel = document.getElementById('c8-slide-panel-' + currentSlide);
        if (targetPanel) {
            targetPanel.classList.add('active');
            targetPanel.style.display = 'block';
        }

        // 4. Render charts if needed
        if (currentSlide === 9) {
            setTimeout(initC8VisitasChart, 60);
        }
        if (currentSlide === 16) {
            setTimeout(initC8CrmChart, 60);
        }

        // 5. Scroll smoothly to top of visor
        if (shouldScroll) {
            var scroller = document.getElementById('scrollContainer') || window;
            var visorNav = document.getElementById('c8-visor-nav');
            if (scroller && visorNav && scroller.getBoundingClientRect) {
                var sRect = scroller.getBoundingClientRect();
                var vRect = visorNav.getBoundingClientRect();
                var diff = scroller.scrollTop + (vRect.top - sRect.top) - 10;
                scroller.scrollTo({ top: Math.max(0, diff), behavior: 'smooth' });
            }
        }
    };

    window.nextC8Slide = function() {
        if (currentSlide < totalSlides) {
            window.goToC8Slide(currentSlide + 1, true);
        }
    };

    window.prevC8Slide = function() {
        if (currentSlide > 1) {
            window.goToC8Slide(currentSlide - 1, true);
        }
    };

    window.switchC8Eje = function(ejeId) {
        var sList = ejeMapping[ejeId];
        if (sList && sList.length > 0) {
            window.goToC8Slide(sList[0], true);
        }
    };

    function initC8VisitasChart() {
        var canvas = document.getElementById('c8VisitasChart');
        if (!canvas || !window.Chart) return;
        if (window._c8VisitasChartInstance) {
            window._c8VisitasChartInstance.destroy();
        }
        var ctx = canvas.getContext('2d');
        window._c8VisitasChartInstance = new Chart(ctx, {
            type: 'bar',
            data: {
                labels: ['2020', '2021', '2022', '2023', '2024', '2025', '2026*'],
                datasets: [
                    {
                        label: 'Cátedra',
                        data: [3508, 5791, 3051, 2500, 2616, 3974, 2542],
                        backgroundColor: '#F39200',
                        borderRadius: 4
                    },
                    {
                        label: 'Básicas',
                        data: [3219, 4541, 2224, 1962, 1784, 2927, 1988],
                        backgroundColor: '#C8102E',
                        borderRadius: 4
                    },
                    {
                        label: 'Económicas / Admon',
                        data: [555, 869, 671, 396, 772, 1096, 521],
                        backgroundColor: '#1A1A1B',
                        borderRadius: 4
                    }
                ]
            },
            options: {
                responsive: true,
                maintainAspectRatio: false,
                plugins: {
                    legend: { position: 'bottom', labels: { font: { size: 10, weight: 'bold' } } },
                    tooltip: { mode: 'index', intersect: false }
                },
                scales: {
                    x: { grid: { display: false } },
                    y: { beginAtZero: true, grid: { color: '#F1F5F9' } }
                }
            }
        });
    }

    function initC8CrmChart() {
        var canvas = document.getElementById('c8CrmChart');
        if (!canvas || !window.Chart) return;
        if (window._c8CrmChartInstance) {
            window._c8CrmChartInstance.destroy();
        }
        var ctx = canvas.getContext('2d');
        window._c8CrmChartInstance = new Chart(ctx, {
            type: 'doughnut',
            data: {
                labels: [
                    'Acceso Plataforma Virtual (329)',
                    'Restablecer Contraseñas (245)',
                    'Acceso Correo Electrónico (173)',
                    'Info General / Claves (156)',
                    'Info Plataforma Campus (35)',
                    'Info Plataforma Moodle (24)'
                ],
                datasets: [{
                    data: [329, 245, 173, 156, 35, 24],
                    backgroundColor: ['#F39200', '#EA580C', '#C8102E', '#D97706', '#1A1A1B', '#64748B'],
                    borderWidth: 2,
                    borderColor: '#FFFFFF'
                }]
            },
            options: {
                responsive: true,
                maintainAspectRatio: false,
                plugins: {
                    legend: { position: 'bottom', labels: { boxWidth: 10, font: { size: 9 } } }
                }
            }
        });
    }

    window.c8Init = function() {
        window.goToC8Slide(1, false);
    };
})();
